import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { readFileSync, unlinkSync } from 'node:fs';
import { build } from 'esbuild';

const dir = fileURLToPath(new URL('..', import.meta.url));
const output = `${dir}/tests/.post-activity-test.cjs`;
await build({ stdin: { contents: `export { default as router } from './src/routes/posts'; export { pool } from '@workspace/db';`, resolveDir: dir }, outfile: output, bundle: true, platform: 'node', format: 'cjs', external: ['pg-native'], logLevel: 'silent', plugins: [{ name: 'storage', setup(b) {
  b.onLoad({ filter: /lib\/objectStorage\.ts$/ }, () => ({ contents: 'export const createPrivateGetUrl=async p=>p; export const createPrivateUploadUrl=async()=>({}); export const deletePrivateObject=async()=>{};' }));
} }] });
const { router, pool } = createRequire(import.meta.url)(output);
const prefix = `post-test-${randomUUID()}`;
const owner = 1750000000 + Math.floor(Math.random() * 10000000), viewer = owner + 1, other = owner + 2;
const ids = [];
const call = async (path, method, uid, postId, body = {}, extra = {}, query = {}) => {
  const handler = router.stack.find(l => l.route?.path === path && l.route.methods[method])?.route.stack[0].handle;
  assert.ok(handler);
  const res = { statusCode: 200, body: null, set() { return this; }, status(n) { this.statusCode = n; return this; }, json(value) { this.body = value; return this; } };
  await handler({ auth: () => ({ userId: uid ? `${prefix}-${uid}` : null }), params: { postId: String(postId), ...extra }, body, query }, res);
  return res;
};
const activity = (id, uid) => call('/posts/:postId/activity', 'get', uid, id);
const react = (id, uid, kind, active) => call('/posts/:postId/activity', 'put', uid, id, { kind, active });
const comment = (id, uid, text, requestId = randomUUID()) => call('/posts/:postId/comments', 'post', uid, id, { text, requestId });
try {
  await pool.query(readFileSync(new URL('../../../lib/db/migrations/20260910_post_activity.sql', import.meta.url), 'utf8'));
  for (const uid of [owner, viewer, other]) await pool.query('insert into users(uid,clerk_id,name) values($1,$2,$3)', [uid, `${prefix}-${uid}`, prefix]);
  for (let i = 0; i < 2; i++) ids.push((await pool.query('insert into posts(owner_user_id,image_object_path,caption) values($1,$2,$3) returning id', [owner, `/objects/${prefix}`, 'Caption'])).rows[0].id);
  const [post, second] = ids;
  assert.equal((await react(post, null, 'like', true)).statusCode, 401);
  assert.equal((await react(post, viewer, 'invalid', true)).statusCode, 400);
  assert.equal((await activity('invalid', viewer)).statusCode, 400);
  assert.equal((await activity(2147483647, viewer)).statusCode, 404);
  await Promise.all([react(post, viewer, 'like', true), react(post, viewer, 'like', true)]);
  assert.deepEqual((await activity(post, viewer)).body, { liked: true, saved: false, likeCount: 1, commentCount: 0 });
  assert.equal((await activity(post, other)).body.liked, false);
  await react(post, other, 'like', true);
  await react(post, viewer, 'like', false);
  await react(post, viewer, 'like', false);
  assert.equal((await activity(post, viewer)).body.likeCount, 1);
  await react(post, viewer, 'save', true);
  const saved = uid => call('/posts/saved', 'get', uid);
  assert.equal((await saved(null)).statusCode, 401);
  assert.deepEqual((await saved(viewer)).body.posts.map(p => p.id), [post]);
  assert.deepEqual((await saved(other)).body.posts, []);
  await react(post, viewer, 'save', false);
  assert.deepEqual((await saved(viewer)).body.posts, []);
  assert.equal((await comment(post, null, 'Hello')).statusCode, 401);
  assert.equal((await comment(post, viewer, '  ')).statusCode, 400);
  assert.equal((await comment(post, viewer, 'x'.repeat(1001))).statusCode, 400);
  const requestId = randomUUID();
  const duplicated = await Promise.all([comment(post, viewer, ' Hello ', requestId), comment(post, viewer, ' Hello ', requestId)]);
  assert.ok(duplicated.every(r => r.statusCode === 200));
  assert.equal((await activity(post, viewer)).body.commentCount, 1);
  assert.equal((await comment(second, viewer, 'Hello', requestId)).statusCode, 409);
  const first = (await call('/posts/:postId/comments', 'get', viewer, post)).body.comments[0];
  assert.equal(first.text, 'Hello');
  const remove = (uid, id, target = post) => call('/posts/:postId/comments/:commentId', 'delete', uid, target, {}, { commentId: String(id) });
  assert.equal((await remove(other, first.id)).statusCode, 404);
  assert.equal((await remove(viewer, first.id, second)).statusCode, 404);
  assert.equal((await remove(viewer, first.id)).statusCode, 200);
  await comment(post, viewer, 'Moderate this');
  const next = (await call('/posts/:postId/comments', 'get', owner, post)).body.comments[0];
  assert.equal((await remove(owner, next.id)).statusCode, 200);
  for (let i = 0; i < 35; i++) await comment(post, viewer, `Comment ${i}`);
  const page1 = (await call('/posts/:postId/comments', 'get', viewer, post)).body;
  assert.equal(page1.comments.length, 30);
  const page2 = (await call('/posts/:postId/comments', 'get', viewer, post, {}, {}, { before: String(page1.nextCursor) })).body;
  assert.equal(page2.comments.length, 5);
  assert.equal(page2.nextCursor, null);
  assert.equal(new Set([...page1.comments, ...page2.comments].map(c => c.id)).size, 35);
  await react(post, viewer, 'save', true);
  await pool.query('insert into user_blocks(blocker_user_id,blocked_user_id) values($1,$2)', [owner, viewer]);
  assert.equal((await react(post, viewer, 'like', true)).statusCode, 404);
  assert.equal((await comment(post, viewer, 'Blocked')).statusCode, 404);
  assert.equal((await activity(post, viewer)).statusCode, 404);
  assert.deepEqual((await saved(viewer)).body.posts, []);
  await pool.query('delete from posts where id=$1', [post]);
  assert.equal((await pool.query('select count(*)::int as n from post_reactions where post_id=$1', [post])).rows[0].n, 0);
  assert.equal((await pool.query('select count(*)::int as n from post_comments where post_id=$1', [post])).rows[0].n, 0);
  console.log('PASS: persistent reactions, duplicate protection, private saves, authenticated comments, pagination, author/owner deletion, blocked users, and cascading cleanup.');
} finally {
  await pool.query('delete from users where uid=ANY($1::int[])', [[owner, viewer, other]]);
  await pool.end();
  unlinkSync(output);
}
