// Build transparent effect assets, never process a recorded stream or Moment.
// Requires ffmpeg. Source art: Noto Emoji, Apache 2.0 (assets/moment-proof).
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
const mobile = fileURLToPath(new URL("../", import.meta.url));
const temp = mkdtempSync(join(tmpdir(), "proof-frames-"));
try {
  const crown = join(mobile, "assets/moments/crown.png");
  const frames = [];
  // 0 is transparent. 1..43 animate at 20fps from 50ms through 2150ms.
  for (let i = 0; i < 44; i++) {
    const t = i * 50,
      p = Math.min(t / 380, 1);
    const exit = Math.max(0, Math.min((t - 1480) / 720, 1));
    const scale =
      t < 380
        ? 0.4 + 0.6 * (1 + 3.2 * (p - 1) ** 3 + 2.2 * (p - 1) ** 2)
        : 1 + 0.12 * exit ** 2;
    const size = Math.round(280 * scale);
    const alpha = Math.min(t / 180, 1) * (1 - exit ** 2);
    const y = Math.round(384 - size / 2 - 208 * exit ** 2);
    const png = execFileSync(
      "ffmpeg",
      [
        "-v",
        "error",
        "-i",
        crown,
        "-vf",
        `format=rgba,scale=${size}:${size}:flags=lanczos,colorchannelmixer=aa=${alpha},pad=384:576:(ow-iw)/2:${y}:color=black@0,format=rgba`,
        "-frames:v",
        "1",
        "-threads",
        "1",
        "-c:v",
        "png",
        "-f",
        "image2pipe",
        "pipe:1",
      ],
      { maxBuffer: 1024 * 1024 },
    );
    frames.push(png.toString("base64"));
  }
  writeFileSync(
    join(mobile, "utils/momentGiftFrames.ts"),
    "// Generated by scripts/generate-moment-gift-frames.mjs. Noto Emoji, Apache 2.0.\n// Fixed RGBA sprite frames: 384x576. Frame 0 is fully transparent.\nexport const giftFramesBase64: readonly string[] = " +
      JSON.stringify(frames, null, 2) +
      ";\n",
  );
  console.log(`Generated ${frames.length} transparent effect frames.`);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
